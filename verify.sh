#!/usr/bin/env bash
# verify.sh — jinjya-api (Cloudflare Workers) 検証ハーネス
# 設置先: /Users/eightman/dev/apps/jinjya-api/verify.sh
#
# 使い方:
#   ./verify.sh          高速検証: ユニットテスト (npm test -- --run)
#   ./verify.sh --check  環境確認と実行ステップの表示のみ（何も実行しない）
#   ./verify.sh --full   高速検証 + wrangler types 生成差分確認
#
# 方針:
#   - node_modules が無い場合は npm install を勝手に実行せず SKIP 表示する
#   - 既存ファイルは変更しない（型定義の差分確認は一時ファイルに生成して比較）
#   - bash 3.2 / BSD コマンド互換

set -euo pipefail
cd "$(cd "$(dirname "$0")" && pwd)"

MODE="fast"
case "${1:-}" in
	--check) MODE="check" ;;
	--full)  MODE="full" ;;
	"") ;;
	*)
		echo "不明な引数: $1" >&2
		echo "使い方: ./verify.sh [--check|--full]" >&2
		exit 1
		;;
esac

STEP=0
TOTAL=0
step() {
	STEP=$((STEP + 1))
	echo ""
	echo "[${STEP}/${TOTAL}] $1"
}
fail() {
	echo "  NG: $1" >&2
	echo ""
	echo "VERIFY FAIL"
	exit 1
}
skip() {
	echo "  SKIP: $1"
}
have() {
	command -v "$1" >/dev/null 2>&1
}

# ---- 環境情報の収集 ------------------------------------------------------
NM_OK=0
if [ -d node_modules ]; then NM_OK=1; fi

WRANGLER_CONFIG=""
for f in wrangler.toml wrangler.json wrangler.jsonc; do
	if [ -f "$f" ] && [ -z "$WRANGLER_CONFIG" ]; then WRANGLER_CONFIG="$f"; fi
done

# ---- --check: 環境確認とステップ表示のみ ---------------------------------
if [ "$MODE" = "check" ]; then
	TOTAL=4
	step "node / npm の確認"
	if have node; then
		echo "  node: OK ($(node --version))"
	else
		fail "node が見つかりません"
	fi
	if have npm; then
		echo "  npm:  OK ($(npm --version))"
	else
		fail "npm が見つかりません"
	fi

	step "node_modules の確認"
	if [ "$NM_OK" -eq 1 ]; then
		echo "  OK: インストール済み"
	else
		echo "  未インストール: npm install が必要です（無印/--full のテスト系ステップは SKIP されます）"
	fi

	step "wrangler 設定ファイルの確認"
	if [ -n "$WRANGLER_CONFIG" ]; then
		echo "  OK: $WRANGLER_CONFIG"
	else
		echo "  なし: wrangler.toml が存在しません（wrangler.toml.example を参照）。--full の cf-typegen 差分確認は SKIP されます"
	fi

	step "実行ステップ一覧"
	echo "  無印  : [1/1] ユニットテスト (npm test -- --run / vitest)"
	echo "  --full: [1/2] ユニットテスト (npm test -- --run / vitest)"
	echo "          [2/2] wrangler types 生成差分確認 (npm run cf-typegen)"
	echo ""
	echo "VERIFY PASS"
	exit 0
fi

# ---- 無印 / --full 共通の前提確認 ----------------------------------------
if ! have node || ! have npm; then
	TOTAL=1
	step "環境確認"
	fail "node / npm が見つかりません"
fi

TOTAL=1
if [ "$MODE" = "full" ]; then TOTAL=2; fi

# ---- [1] ユニットテスト --------------------------------------------------
# package.json の "test": "vitest"。watch モード回避のため --run を付与する。
step "ユニットテスト (npm test -- --run)"
if [ "$NM_OK" -eq 0 ]; then
	skip "node_modules がありません。npm install が必要です"
else
	if ! npm test -- --run; then
		fail "ユニットテストが失敗しました"
	fi
	echo "  OK: テスト通過"
fi

# ---- [2] wrangler types 生成差分確認（--full のみ） -----------------------
# 既存の worker-configuration.d.ts を変更しないため、一時ファイルへ生成して比較する。
# 生成ヘッダ行（実行コマンド文字列を含む "// Generated by Wrangler..."）は比較から除外する。
if [ "$MODE" = "full" ]; then
	step "wrangler types 生成差分確認 (npm run cf-typegen)"
	if [ -z "$WRANGLER_CONFIG" ]; then
		skip "wrangler 設定ファイル(wrangler.toml 等)が無いため実行できません（wrangler.toml.example を参照）"
	elif [ "$NM_OK" -eq 0 ]; then
		skip "node_modules がありません。npm install が必要です"
	elif [ ! -f worker-configuration.d.ts ]; then
		skip "worker-configuration.d.ts が存在しないため比較できません（npm run cf-typegen で生成してください）"
	else
		TMP_TYPES="${TMPDIR:-/tmp}/jinjya_verify_types_$$.d.ts"
		trap 'rm -f "${TMP_TYPES:-}"' EXIT
		if ! npm run cf-typegen -- "$TMP_TYPES"; then
			fail "wrangler types の生成に失敗しました"
		fi
		if diff \
			<(grep -v '^// Generated by Wrangler' worker-configuration.d.ts) \
			<(grep -v '^// Generated by Wrangler' "$TMP_TYPES") >/dev/null; then
			echo "  OK: worker-configuration.d.ts は最新です"
		else
			echo "  差分検出。現行との差分(先頭40行):"
			diff \
				<(grep -v '^// Generated by Wrangler' worker-configuration.d.ts) \
				<(grep -v '^// Generated by Wrangler' "$TMP_TYPES") | head -40 || true
			fail "型定義が古くなっています。npm run cf-typegen を実行して worker-configuration.d.ts を更新してください"
		fi
		rm -f "$TMP_TYPES"
	fi
fi

echo ""
echo "VERIFY PASS"
